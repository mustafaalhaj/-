  Future<Map<String, String>> getDailyHadith() async {
    try {
      await Future.delayed(const Duration(milliseconds: 500));
      final dayOfYear = DateTime.now().day + (DateTime.now().month * 31);
      return _hadiths[dayOfYear % _hadiths.length];
    } catch (e) {
      return _hadiths[0];
    }
  }

  Future<Map<String, String>> getHadithByIndex(int index) async {
    try {
      await Future.delayed(const Duration(milliseconds: 300));
      if (index >= 0 && index < _hadiths.length) {
        return _hadiths[index];
      }
      return _hadiths[0];
    } catch (e) {
      return _hadiths[0];
    }
  }

  int getTotalHadiths() {
    return _hadiths.length;
  }

  List<Map<String, String>> searchHadiths(String query) {
    if (query.isEmpty) return [];

    return _hadiths.where((h) {
      final text = h['hadith'] ?? '';
      final explanation = h['explanation'] ?? '';
      return text.contains(query) || explanation.contains(query);
    }).toList();
  }
